"""Deterministic draft reports with original evidence and explicit epistemic labels."""
import copy
from .persistent_ingestion import _encode, _checksum
from .analysis_transactions import assessment_is_current, _origin


def report_input_digest(state):
    return _checksum(_encode({k:v for k,v in state.snapshot().items() if k not in {'outputs','change_log','acceptance_records','research_agendas'}}))


def build_report(state,*,report_id,actor,timestamp,include_evaluation_evidence=False):
    def evidence_snapshot(eid):
        item=copy.deepcopy(state.evidence[eid])
        return dict(evidence_id=eid,evidence=item,source=copy.deepcopy(state.sources.get(item.get('source_id'))),
                    synthetic=item.get('synthetic') is True)

    claims=[]
    for cid,claim in sorted(state.claims.items()):
        evidence=[evidence_snapshot(eid) for eid in claim.get('evidence_ids',[])]
        claims.append(dict(claim_id=cid,interpretation=copy.deepcopy(claim),evidence_origin=_origin(state,claim.get('evidence_ids',[])),evidence=evidence,
                           epistemic_label='hypothesis' if claim.get('disposition') in {'hypothesis','promote_to_hypothesis'} or claim.get('status')=='hypothesis' else 'advisory interpretation'))
    assessments=[dict(assessment=copy.deepcopy(item),current=assessment_is_current(state,aid)) for aid,item in sorted(getattr(state,'assessments',{}).items())]
    from .workflow import research_content_digest
    stage_currency={phase:digest==research_content_digest(state) for phase,digest in state.workflow['record_bindings'].items()}
    if state.workflow.get('workflow_version') in {2,3}:
        from .double_diamond import stage_currency as dd_currency
        stage_currency=dd_currency(state)
    result=dict(stage_currency=stage_currency,report_id=report_id,status='draft',publication_authorized=False,generated_by=actor,generated_at=timestamp,
        input_digest=report_input_digest(state),research_id=state.research_id,brief=copy.deepcopy(state.brief),scope=copy.deepcopy(state.scope),questions=copy.deepcopy(state.research_questions),
        workflow=copy.deepcopy(state.workflow),claims=claims,assessments=assessments,uncertainties=copy.deepcopy(state.uncertainties),
        contradictions=copy.deepcopy(state.contradictions),hypotheses=copy.deepcopy(state.hypotheses),gates=copy.deepcopy(state.human_gates),
        limitations=['Draft interpretations and test outcomes are recorded assertions, not independent validation.',
                    'Synthetic evidence is a demonstration and cannot establish real-world findings.',
                    'No external publication is performed; approval identities depend on host authentication.'])
    if state.workflow.get('workflow_version') in {2,3}:
        evaluations=state.workflow['records'].get('deliver',{}).get('evaluations',[])
        result['evaluation_origins']={item['evaluation_id']:_origin(state,item['evidence_ids']) for item in evaluations}
        if include_evaluation_evidence:
            claim_evidence={item['evidence_id'] for claim in claims for item in claim['evidence']}
            evaluation_evidence={eid for evaluation in evaluations for eid in evaluation['evidence_ids']}
            result['evaluation_evidence']=[evidence_snapshot(eid) for eid in sorted(evaluation_evidence-claim_evidence)]
        result['research_scope_note']='Recorded research evaluations and recommendations; no automatic experiment validation or product delivery.'
    if state.workflow.get('workflow_version')==3:
        from .double_diamond import decision_trace
        result['decision_trace']=decision_trace(state)
    result['content_digest']=_checksum(_encode(result))
    return result


def report_is_current(state,report_id):return state.outputs[report_id]['input_digest']==report_input_digest(state)


def render_markdown(report):
    import html
    import json
    import re
    def safe(value):
        text=value if isinstance(value,str) else json.dumps(value,ensure_ascii=False,sort_keys=True)
        text=html.escape(text,quote=False).replace('\n',' ')
        return re.sub(r'([\\`*_{}\[\]()#+.!|>~-])',r'\\\1',text)
    def field(label,value):return '- **'+label+':** '+safe(value)
    lines=['# Research draft','','DRAFT — this export does not authorize publication.','',
        field('Research',report['research_id']),field('Report digest',report['content_digest']),
        field('Generated by',report['generated_by']),field('Generated at',report['generated_at']),
        '','## Brief and scope',safe(report['brief'].get('text',report['brief'])),safe(report['scope'].get('text',report['scope'])),
        '','## Questions']
    lines += ['- '+safe(q.get('question',q)) for q in report['questions']]
    workflow=report['workflow']
    lines += ['','## Workflow',field('Outcome',workflow['status']),field('Stopping reason',workflow.get('stopping_reason','Unspecified'))]
    phases=('discover','define','develop','deliver') if workflow.get('workflow_version') in {2,3} else ('discovery','definition','alternatives','synthesis')
    if workflow.get('workflow_version') in {2,3}:
        lines += ['',field('Recorded phase visits',len(workflow['visits'])),field('Visit budget',workflow['max_visits']),field('Iteration history',workflow['history'])]
    for phase in phases:
        if phase not in workflow['records']:continue
        record=workflow['records'][phase]
        lines += ['','### '+phase.capitalize(),field('Research content binding','current' if report['stage_currency'][phase] else 'STALE — content changed after recording')]
        if phase=='develop':
            for item in record['alternatives']:
                lines += ['',field('Alternative',item['alternative_id']),field('Hypothesis',item['hypothesis']),field('Proposed test',item['test']),field('Evidence IDs',item['evidence_ids']),field('Limitations',item['limitations'])]
        elif phase=='alternatives':
            for item in record['alternatives']:
                lines += ['',field('Alternative',item['alternative_id']),field('Hypothesis',item['hypothesis']),field('Recorded test',item['test']),
                    field('Recorded outcome',item['outcome']),field('Claim IDs',item['claim_ids']),field('Evidence IDs',item['evidence_ids']),field('Limitations',item['limitations'])]
        else:lines += [field(key.replace('_',' ').capitalize(),value) for key,value in record.items()]
        if phase=='deliver':lines += [field('Evaluation evidence origins',report.get('evaluation_origins',{})),field('Research scope',report.get('research_scope_note',''))]
    if workflow.get('workflow_version') in {2,3}:
        latest={v['phase']:v['visit_id'] for v in workflow['visits']}
        lines += ['','## Original phase visits']
        for visit in workflow['visits']:
            current=visit['phase'] in workflow['records'] and latest[visit['phase']]==visit['visit_id']
            lines += ['',field('Visit',visit['visit_id']+' '+visit['phase']),field('Status','current' if current else 'superseded'),field('Reason',visit['reason']),field('Original record',visit['record'])]
    if report.get('decision_trace'):
        trace=report['decision_trace'];lines += ['','## Decision against success criteria',field('Selected alternative',trace['selected_alternative_id']),field('Decision',trace['decision']),field('Assessment basis',trace['verification'])]
        for row in trace['criteria']:
            lines += ['',field('Criterion',row['criterion']),field('Outcome',row['outcome']),field('Reason',row['rationale']),field('Evaluation IDs',row['evaluation_ids']),field('Evidence IDs',row['evidence_ids']),field('Evidence origin',row['evidence_origin']),field('Next research',row['next_research'] or 'No additional action recorded')]
    lines += ['','## Claims and evidence']
    for item in report['claims']:
        claim=item['interpretation']
        lines += ['', '### Claim '+safe(item['claim_id']),safe(claim['claim']),field('Interpretation label',item['epistemic_label']),
            field('Evidence origin',item['evidence_origin']),field('Claim type',claim.get('claim_type','descriptive')),
            field('Disposition',claim.get('disposition','unknown')),field('Status',claim.get('status','unknown')),
            field('Confidence',claim.get('confidence','unspecified')),field('Material uncertainty IDs',claim.get('material_uncertainties',[]))]
        for evidence in item['evidence']:
            record=evidence['evidence'];source=evidence['source'] or record.get('metadata',{})
            lines += ['','SYNTHETIC EXAMPLE' if evidence['synthetic'] else 'NON-SYNTHETIC SOURCE RECORD (not a truth guarantee)',
                field('Evidence ID',evidence['evidence_id']),field('Passage/finding',record.get('finding','')),
                field('Exact location',record.get('exact_location','unspecified')),field('Source ID',record.get('source_id','unspecified')),
                field('Title',source.get('title','Synthetic fixture / no real-source record')),field('Publisher',source.get('publisher','unspecified')),
                field('URL',source.get('url',record.get('metadata',{}).get('url','unspecified'))),field('Source provenance',source.get('provenance',record.get('provenance','unspecified'))),field('Retrieved at',source.get('retrieved_at','unspecified')),field('Published at',source.get('published_at','unspecified')),field('Independence cluster',source.get('independence_cluster',record.get('independence_cluster','unspecified')))]
    if report.get('evaluation_evidence'):
        lines += ['','## Additional evidence linked directly to evaluations']
        for item in report['evaluation_evidence']:
            record=item['evidence']
            source=item['source'] or record.get('metadata',{})
            lines += ['','SYNTHETIC EXAMPLE' if item['synthetic'] else 'REVIEWED SOURCE RECORD',
                field('Evidence ID',item['evidence_id']),field('Passage/finding',record.get('finding','')),
                field('Exact location',record.get('exact_location','unspecified')),
                field('Title',source.get('title','unspecified')),field('Publisher',source.get('publisher','unspecified')),
                field('Source reference',source.get('url','unspecified'))]
    lines += ['','## Assessments']
    for item in report['assessments']:
        assessment=item['assessment']
        lines += ['',field('Assessment',assessment.get('assessment_id','unknown')),field('Freshness','current' if item['current'] else 'STALE'),field('Details',assessment)]
    if not report['assessments']:lines += ['No recorded assessments.']
    for title,key in [('Hypotheses','hypotheses'),('Contradictions','contradictions'),('Uncertainty','uncertainties')]:
        lines += ['', '## '+title]
        if not report[key]:lines += ['No separate records.']
        for identifier,record in sorted(report[key].items()):
            lines += ['',field('ID',identifier)]
            lines += [field(name.replace('_',' ').capitalize(),value) for name,value in record.items()]
    lines += ['','## Gate decisions at generation']
    for gid,gate in sorted(report['gates'].items()):
        lines += ['- '+safe(gid)+': '+safe(gate.get('status','unknown'))+'; type '+safe(gate.get('gate_type','unknown'))+'; decision actor '+safe(gate.get('decision_actor','not recorded'))]
    lines += ['','## Limitations']+['- '+safe(item) for item in report['limitations']]
    return '\n'.join(lines)+'\n'


def export_report(database,report_id,destination,*,format='markdown',allow_stale=False):
    """Verify and export a saved draft from one read-only database snapshot."""
    import json
    import tempfile
    from pathlib import Path
    from contextlib import closing
    from .checkpoints import _ReadOnlySource, _destination, _publish
    from .persistent_ingestion import PersistentEvidenceStore
    from .review_ledger import ReviewLedger
    if format not in {'markdown','json'}:raise ValueError('format must be markdown or json')
    if type(allow_stale) is not bool:raise ValueError('allow_stale must be boolean')
    destination=_destination(destination)
    source=_ReadOnlySource(database)
    store=object.__new__(PersistentEvidenceStore);store.ledger=object.__new__(ReviewLedger)
    with closing(source._connect()) as db:
        db.execute('BEGIN')
        state,revision,_,_=store._verify_integrity(db)
        if report_id not in state.outputs or 'content_digest' not in state.outputs[report_id]:raise KeyError('unknown saved report')
        report=state.outputs[report_id];current=report_is_current(state,report_id)
        if not current and not allow_stale:raise ValueError('saved report is stale; regenerate or explicitly allow stale draft')
        content=render_markdown(report) if format=='markdown' else json.dumps(report,ensure_ascii=False,indent=2)+'\n'
    if not current and format=='markdown':content='STALE DRAFT — research or gate state has changed since generation.\n\n'+content
    if format=='json':content=json.dumps(dict(report=report,current_at_export=current,export_state_revision=revision),ensure_ascii=False,indent=2)+'\n'
    with tempfile.TemporaryDirectory(prefix='.dd-report-',dir=destination.parent) as temp:
        staged=Path(temp)/'report';staged.write_text(content,encoding='utf-8');_publish(staged,destination,None)
    return dict(report_id=report_id,destination=str(destination),content_digest=report['content_digest'],state_revision=revision,current=current,status='draft')
